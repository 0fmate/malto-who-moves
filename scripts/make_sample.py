"""Build data_sample/: small CSV excerpts + SUMMARY.md, so Claude never reads the raw data.

Usage: python scripts/make_sample.py [--rows-per-role 10]
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from whomoves.config import load_config  # noqa: E402
from whomoves.io import load_csv  # noqa: E402

SMALL_CSVS = ["train_videos", "train_alarms", "test_videos", "sample_submission"]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rows-per-role", type=int, default=10)
    args = parser.parse_args()

    cfg = load_config()
    data_dir, out_dir = cfg["paths"]["data_dir"], cfg["paths"]["sample_dir"]
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = ["# Data summary (generated by scripts/make_sample.py)", ""]

    for name in SMALL_CSVS:
        df = load_csv(data_dir, name)
        df.head(20).to_csv(out_dir / f"{name}_head.csv", index=False)
        lines += [f"## {name}.csv", f"- rows: {len(df)}", f"- columns: {', '.join(df.columns)}", ""]

    videos = load_csv(data_dir, "train_videos")
    lines += ["## train_videos by source", "```",
              videos.groupby("source_dataset")
                    .agg(n_videos=("video_id", "size"), minutes=("duration_s", lambda s: s.sum() / 60))
                    .round(1).to_string(),
              "```", ""]

    tracks = load_csv(data_dir, "train_tracks")
    # A few rows per role, so that every role appears in the sample.
    sample = tracks.groupby("role", group_keys=False).apply(
        lambda g: g.sample(min(len(g), args.rows_per_role), random_state=0)
    )
    sample.sort_values(["video_id", "track_id", "frame"]).to_csv(out_dir / "train_tracks_sample.csv", index=False)

    per_track = tracks.groupby(["video_id", "track_id"]).agg(
        role=("role", "first"), cls=("class", "first"), n_frames=("frame", "size"),
        h_median=("h", "median"), moving_frac=("moving", "mean"),
    )
    lines += [
        "## train_tracks.csv",
        f"- rows: {len(tracks)}, tracks: {len(per_track)}",
        f"- columns: {', '.join(tracks.columns)}",
        "", "### tracks per role and class", "```",
        per_track.groupby(["role", "cls"]).size().unstack(fill_value=0).to_string(),
        "```", "", "### box height (px) and moving fraction per role", "```",
        per_track.groupby("role")[["h_median", "moving_frac", "n_frames"]]
                 .describe(percentiles=[0.1, 0.5, 0.9]).round(2).T.to_string(),
        "```", "",
    ]

    (out_dir / "SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(list(out_dir.iterdir()))} files to {out_dir}")


if __name__ == "__main__":
    main()
